// Regenerates src/lib/geo/swMauOutline.js from OpenStreetMap.
//   node scripts/fetch-sw-mau-outline.mjs
// The feature is relation 16054773, "South West Mau Forest" (natural=wood): a
// forest-cover polygon mapped by OpenStreetMap volunteers. It is NOT the
// gazetted reserve boundary. Data © OpenStreetMap contributors, ODbL 1.0.
import { writeFileSync } from 'node:fs'

const OSM = 'R16054773'
const TOLERANCE_DEG = 0.0003 // ~30 m; Nominatim simplifies to this
const url = new URL('https://nominatim.openstreetmap.org/lookup')
url.search = new URLSearchParams({
  osm_ids: OSM,
  format: 'geojson',
  polygon_geojson: '1',
  polygon_threshold: String(TOLERANCE_DEG),
}).toString()

const response = await fetch(url, { headers: { 'user-agent': 'ForestOS-Ops-prototype (outline fetch script)' } })
if (!response.ok) throw new Error(`Nominatim answered ${response.status}`)
const feature = (await response.json()).features?.[0]
if (feature?.geometry?.type !== 'Polygon') throw new Error(`Expected one Polygon, got ${feature?.geometry?.type}`)

const round = (n) => Number(n.toFixed(5))
const rings = feature.geometry.coordinates.map((ring) => ring.map(([lon, lat]) => [round(lon), round(lat)]))

const body = `// The South West Mau Forest outline: forest cover as mapped in OpenStreetMap.
// Generated by scripts/fetch-sw-mau-outline.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
//
// READ THIS BEFORE USING IT AS A BOUNDARY: this is an OpenStreetMap
// \`natural=wood\` polygon (relation ${OSM.slice(1)}), traced by volunteers. It covers
// about 21,400 ha: roughly a third of the gazetted South West Mau Forest Reserve
// (about 60,000 ha, Kenya Forest Service). It is a forest-cover outline, not a
// survey or legal boundary. Replace it with the boundary from KFS
// or the Survey of Kenya when that is available; nothing else needs to change.
//
// Data © OpenStreetMap contributors, licensed under the ODbL 1.0
// (https://www.openstreetmap.org/copyright). This extract stays under that licence.
//
// rings[0] is the outer ring; any others are holes (clearings inside the forest).
// Each ring is closed [lon, lat] pairs, simplified to about 30 m.

export const SW_MAU_OUTLINE = {
  name: 'South West Mau Forest',
  osm: 'relation/${OSM.slice(1)}',
  attribution: '© OpenStreetMap contributors',
  licence: 'ODbL 1.0',
  rings: ${JSON.stringify(rings)},
}
`
writeFileSync(new URL('../src/lib/geo/swMauOutline.js', import.meta.url), body)
console.log(`Wrote ${rings.length} rings, ${rings.map((r) => r.length).join(' / ')} vertices`)
